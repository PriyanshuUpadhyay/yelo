def register(subparsers):
    parser = subparsers.add_parser(
        "shell-init",
        help="print the shell wrappers to eval",
        description=__doc__.splitlines()[0],
    )
    parser.add_argument("shell", choices=("zsh",))
    parser.set_defaults(run=run)
    return parser
