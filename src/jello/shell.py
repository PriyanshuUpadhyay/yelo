def render_zsh(version):
    """The whole init script. Pure: same version in, same bytes out (law L6)."""
    return f"{VERSION_PREFIX}{version}\n{TEMPLATE}"


def cache_dir(home=None):
    base = os.environ.get("XDG_CACHE_HOME")
    if not base:
        base = os.path.join(os.path.expanduser("~") if home is None else home, ".cache")
    return os.path.join(base, "jello")


def cache_path(home=None):
    return os.path.join(cache_dir(home), CACHE_NAME)


def read_cache(version, home=None):
    """The cached text when its first line carries this version, else None. The only
    invalidation there is: a cache from another version is re-rendered over."""
    path = cache_path(home)
    try:
        with open(path, encoding="utf-8") as handle:
            text = handle.read()
    except (OSError, UnicodeDecodeError):
        return None
    first = text.partition("\n")[0]
    return text if first == f"{VERSION_PREFIX}{version}" else None


def write_cache(text, home=None):
    """Temp file and rename, so a shell that evaluates the cache never reads half a script."""
    path = cache_path(home)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    descriptor, temporary = tempfile.mkstemp(dir=os.path.dirname(path), prefix=f".{CACHE_NAME}.")
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8") as handle:
            handle.write(text)
            handle.flush()
            os.fsync(handle.fileno())
        os.chmod(temporary, stat.S_IRUSR | stat.S_IWUSR | stat.S_IRGRP | stat.S_IROTH)
        os.replace(temporary, path)
    except BaseException:
        try:
            os.unlink(temporary)
        except OSError:
            pass
        raise
    return path


def cached_text(version, home=None):
    """The text to print: the cache when it is current, else a fresh render written over it.
    A cache that cannot be written is not an error -- the script is still printed."""
    text = read_cache(version, home)
    if text is not None:
        return text
    text = render_zsh(version)
    try:
        write_cache(text, home)
    except OSError:
        pass
    return text


